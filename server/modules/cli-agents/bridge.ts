import net from 'node:net';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { LATEST_PROTOCOL_VERSION, SUPPORTED_PROTOCOL_VERSIONS } from '@modelcontextprotocol/server';
import { nodeRuntime } from './proc.js';

/**
 * Local bridge between a CLI agent and TeamBot: a tiny stdio MCP server (script below) that the CLI starts
 * from its per-run MCP configuration. The script holds no logic and no secrets of its own; it forwards over
 * a local named pipe / unix socket (never TCP) to this process, where the run's handlers live:
 *  - `permission_prompt` (Claude Code's `--permission-prompt-tool`): the TeamBot Broker decides.
 *  - TeamBot's own tools (memory, team/delegation, browser, desktop, skills, routines, connected apps, …)
 *    for this one run, with the bot's access mode, tool policy and approvals (see toolhost.ts). When a call changed
 *    the run's tool list (tools_load), the script sends `notifications/tools/list_changed` and holds the result until
 *    the CLI listed again (at most 1.5 s), so the CLI's next step already has the loaded tools.
 * Each run gets a random token (read by the script from a per-run file, never from argv), so a request can
 * only reach the run that started it; the token stops working when the run ends. Anything unexpected → deny.
 */

export type PermissionDecision = { behavior: 'allow'; updatedInput: any } | { behavior: 'deny'; message: string };
export type PermissionHandler = (req: { tool_name: string; input: any; tool_use_id?: string }) => Promise<PermissionDecision>;

export interface McpToolSpec {
  name: string;
  description: string;
  inputSchema: any;
  annotations?: Record<string, any>;
  /** E.g. Claude Code's `anthropic/alwaysLoad`: never deferred behind its own tool search. */
  _meta?: Record<string, any>;
}
export interface McpCallResult {
  content: any[];
  isError?: boolean;
  /** The run's tool list changed (tools_load): the script tells the CLI (`notifications/tools/list_changed`). */
  listChanged?: boolean;
}
/** TeamBot tools for one run, served over MCP. */
export interface ToolHandler {
  instructions?(): string;
  list(): Promise<McpToolSpec[]>;
  call(name: string, args: any, signal: AbortSignal): Promise<McpCallResult>;
}
export interface BridgeHandlers {
  permission?: PermissionHandler;
  tools?: ToolHandler;
}
export interface BridgeRegistration {
  token: string;
  /** Per-run file with the token (0600), read by the MCP script at start. */
  tokenFile: string;
  dispose(): void;
}
/** How a CLI should start the TeamBot MCP server (stdio). */
export interface StdioServer {
  command: string;
  args: string[];
  env: Record<string, string>;
}

export const MCP_SERVER_NAME = 'teambot';
export const PERMISSION_TOOL = 'permission_prompt';
export const PERMISSION_TOOL_FQN = `mcp__${MCP_SERVER_NAME}__${PERMISSION_TOOL}`;

/**
 * The protocol revisions the bridge answers on its `initialize` handshake: the official MCP SDK's list (v2), so the
 * script speaks exactly what TeamBot's own MCP client and server speak. The script itself stays dependency-free:
 * the CLI starts it as a plain file from the data folder, outside TeamBot's packages. A client that first probes
 * for the 2026-07-28 revision (`server/discover`) gets "method not found" and falls back to this handshake.
 */
export const BRIDGE_PROTOCOL_VERSIONS: readonly string[] = [...SUPPORTED_PROTOCOL_VERSIONS];

const SCRIPT = String.raw`// TeamBot MCP bridge (stdio). Generated by TeamBot; safe to delete. Holds no logic: forwards to TeamBot.
import fs from 'node:fs';
import net from 'node:net';
import readline from 'node:readline';
const VERSIONS = ${JSON.stringify(BRIDGE_PROTOCOL_VERSIONS)};
const LATEST = ${JSON.stringify(LATEST_PROTOCOL_VERSION)};
const PIPE = process.env.TEAMBOT_BRIDGE;
let TOKEN = process.env.TEAMBOT_BRIDGE_TOKEN || '';
try { if (!TOKEN && process.env.TEAMBOT_BRIDGE_TOKEN_FILE) TOKEN = fs.readFileSync(process.env.TEAMBOT_BRIDGE_TOKEN_FILE, 'utf8').trim(); } catch {}
const PERMISSION = process.env.TEAMBOT_BRIDGE_PERMISSION === '1';
const TOOLS = process.env.TEAMBOT_BRIDGE_TOOLS === '1';
const send = (o) => process.stdout.write(JSON.stringify({ jsonrpc: '2.0', ...o }) + '\n');
const open = new Map();
function ask(method, params, id) {
  return new Promise((resolve) => {
    let buf = '';
    let done = false;
    const finish = (v) => { if (!done) { done = true; open.delete(id); resolve(v); } };
    const s = net.connect(PIPE);
    if (id !== undefined) open.set(id, s);
    s.setEncoding('utf8');
    s.on('connect', () => s.write(JSON.stringify({ token: TOKEN, method, params }) + '\n'));
    s.on('data', (d) => {
      buf += d;
      const i = buf.indexOf('\n');
      if (i >= 0) { try { finish(JSON.parse(buf.slice(0, i))); } catch { finish({ error: 'bad response' }); } s.end(); }
    });
    s.on('error', (e) => finish({ error: String(e && e.message) }));
    s.on('close', () => finish({ error: 'connection closed' }));
  });
}
const permissionTool = {
  name: 'permission_prompt',
  description: 'TeamBot permission gate used by the host for approvals. Do not call this tool yourself.',
  inputSchema: { type: 'object', properties: { tool_name: { type: 'string' }, input: { type: 'object' }, tool_use_id: { type: 'string' } }, required: ['tool_name'] },
};
// After list_changed: the call's result waits until the CLI listed again (at most a moment), so its next step has the tools.
let relisted = null;
readline.createInterface({ input: process.stdin }).on('line', async (line) => {
  let m;
  try { m = JSON.parse(line); } catch { return; }
  if (!m || typeof m !== 'object') return;
  const id = m.id;
  if (m.method === 'initialize') {
    const info = TOOLS ? await ask('info', {}) : {};
    // Answer the client's revision when it is one we speak, else our latest (the client decides whether to go on).
    const asked = m.params && m.params.protocolVersion;
    const result = { protocolVersion: VERSIONS.includes(asked) ? asked : LATEST, capabilities: { tools: { listChanged: true } }, serverInfo: { name: 'teambot', title: 'TeamBot', version: '1.1.0' } };
    if (info && info.result && info.result.instructions) result.instructions = info.result.instructions;
    send({ id, result });
  } else if (m.method === 'tools/list') {
    const tools = PERMISSION ? [permissionTool] : [];
    if (TOOLS) {
      const r = await ask('tools/list', {});
      if (r && r.result && Array.isArray(r.result.tools)) tools.push(...r.result.tools);
      else if (!PERMISSION) return send({ id, error: { code: -32603, message: 'TeamBot niet bereikbaar' + (r && r.error ? ': ' + r.error : '') } });
    }
    send({ id, result: { tools } });
    if (relisted) relisted();
  } else if (m.method === 'tools/call') {
    const p = m.params || {};
    if (p.name === 'permission_prompt' && PERMISSION) {
      const r = await ask('permission', p.arguments || {});
      const decision = r && r.result ? r.result : { behavior: 'deny', message: 'TeamBot-goedkeuring niet bereikbaar' + (r && r.error ? ': ' + r.error : '') };
      send({ id, result: { content: [{ type: 'text', text: JSON.stringify(decision) }] } });
    } else if (TOOLS) {
      const r = await ask('tools/call', { name: String(p.name || ''), arguments: p.arguments || {} }, id);
      if (r && r.listChanged) {
        const again = new Promise((resolve) => { relisted = resolve; setTimeout(resolve, 1500); });
        send({ method: 'notifications/tools/list_changed' });
        await again;
        relisted = null;
      }
      if (r && r.result) send({ id, result: r.result });
      else send({ id, result: { content: [{ type: 'text', text: 'TeamBot-tool niet uitgevoerd' + (r && r.error ? ': ' + r.error : '') }], isError: true } });
    } else send({ id, error: { code: -32602, message: 'Onbekende tool' } });
  } else if (m.method === 'notifications/cancelled') {
    const s = open.get(m.params && m.params.requestId);
    if (s) s.destroy();
  } else if (m.method === 'ping') send({ id, result: {} });
  else if (m.method === 'resources/list') send({ id, result: { resources: [] } });
  else if (m.method === 'resources/templates/list') send({ id, result: { resourceTemplates: [] } });
  else if (m.method === 'prompts/list') send({ id, result: { prompts: [] } });
  else if (id !== undefined && m.method) send({ id, error: { code: -32601, message: 'Method not found' } });
});
`;

export class PermissionBridge {
  private server: net.Server | null = null;
  private starting: Promise<string> | null = null;
  address = '';
  scriptPath = '';
  private handlers = new Map<string, BridgeHandlers>();

  constructor(private dataDir: string) {}

  /** Start the local IPC server (lazy) and make sure the MCP script exists. */
  ensure(): Promise<string> {
    if (this.server && this.address) return Promise.resolve(this.address);
    if (this.starting) return this.starting;
    this.starting = new Promise<string>((resolve, reject) => {
      const dir = path.join(this.dataDir, 'cli-agents');
      fs.mkdirSync(dir, { recursive: true });
      this.scriptPath = path.join(dir, 'teambot-mcp-bridge.mjs');
      fs.writeFileSync(this.scriptPath, SCRIPT);
      const id = crypto.randomBytes(8).toString('hex');
      const addr = process.platform === 'win32' ? `\\\\.\\pipe\\teambot-cli-${process.pid}-${id}` : path.join(os.tmpdir(), `teambot-cli-${process.pid}-${id}.sock`);
      const srv = net.createServer((sock) => this.onConn(sock));
      srv.on('error', (e) => {
        this.starting = null;
        reject(e);
      });
      srv.listen(addr, () => {
        if (process.platform !== 'win32') {
          try {
            fs.chmodSync(addr, 0o600);
          } catch {
            /* ignore */
          }
        }
        this.server = srv;
        this.address = addr;
        resolve(addr);
      });
    });
    return this.starting;
  }

  /**
   * Register the handlers of one run. `dir` is the run's private temp dir (the token file goes there).
   * Passing a bare function registers a permission handler only (backwards compatible).
   */
  register(h: PermissionHandler | BridgeHandlers, dir?: string): BridgeRegistration {
    const handlers: BridgeHandlers = typeof h === 'function' ? { permission: h } : h;
    const token = crypto.randomBytes(24).toString('hex');
    this.handlers.set(token, handlers);
    let tokenFile = '';
    const base = dir || path.join(this.dataDir, 'cli-agents', 'runs');
    try {
      fs.mkdirSync(base, { recursive: true, mode: 0o700 });
      tokenFile = path.join(base, `bridge-${crypto.randomBytes(6).toString('hex')}.token`);
      fs.writeFileSync(tokenFile, token, { mode: 0o600 });
    } catch {
      tokenFile = '';
    }
    return {
      token,
      tokenFile,
      dispose: () => {
        this.handlers.delete(token);
        if (tokenFile) {
          try {
            fs.rmSync(tokenFile, { force: true });
          } catch {
            /* ignore */
          }
        }
      },
    };
  }

  /** The stdio command for one run. The token itself never appears in argv or env (only the file path). */
  stdioServer(reg: BridgeRegistration, o: { permission?: boolean; tools?: boolean } = {}): StdioServer {
    const n = nodeRuntime();
    const env: Record<string, string> = { ...n.env, TEAMBOT_BRIDGE: this.address };
    if (reg.tokenFile) env.TEAMBOT_BRIDGE_TOKEN_FILE = reg.tokenFile;
    else env.TEAMBOT_BRIDGE_TOKEN = reg.token;
    if (o.permission) env.TEAMBOT_BRIDGE_PERMISSION = '1';
    if (o.tools) env.TEAMBOT_BRIDGE_TOOLS = '1';
    return { command: n.command, args: [this.scriptPath], env };
  }

  /** MCP config (as used by `claude --mcp-config <file>`) for one run. */
  mcpConfig(reg: BridgeRegistration | string, o: { permission?: boolean; tools?: boolean } = { permission: true }) {
    const r: BridgeRegistration = typeof reg === 'string' ? { token: reg, tokenFile: '', dispose() {} } : reg;
    const s = this.stdioServer(r, o);
    return { mcpServers: { [MCP_SERVER_NAME]: { type: 'stdio', command: s.command, args: s.args, env: s.env } } };
  }

  private onConn(sock: net.Socket) {
    let buf = '';
    let replied = false;
    const ac = new AbortController();
    sock.setEncoding('utf8');
    sock.setTimeout(0);
    const reply = (o: any) => {
      replied = true;
      try {
        sock.end(JSON.stringify(o) + '\n');
      } catch {
        /* ignore */
      }
    };
    sock.on('error', () => {
      /* client went away */
    });
    // The CLI cancelled the call (or exited): stop the tool.
    sock.on('close', () => {
      if (!replied) ac.abort(new Error('Afgebroken door de CLI'));
    });
    sock.on('data', async (d: string) => {
      buf += d;
      if (buf.length > 4_000_000) return sock.destroy();
      const i = buf.indexOf('\n');
      if (i < 0) return;
      const line = buf.slice(0, i);
      buf = '';
      let msg: any;
      try {
        msg = JSON.parse(line);
      } catch {
        return reply({ error: 'bad request' });
      }
      const h = typeof msg?.token === 'string' && msg.token ? this.handlers.get(msg.token) : undefined;
      if (!h) return reply({ error: 'unknown token' });
      const p = msg.params && typeof msg.params === 'object' ? msg.params : {};
      try {
        if (msg.method === 'permission' && h.permission) {
          try {
            const result = await h.permission({ tool_name: String(p.tool_name || ''), input: p.input ?? {}, tool_use_id: p.tool_use_id });
            return reply({ result });
          } catch (e: any) {
            return reply({ result: { behavior: 'deny', message: `Geweigerd door TeamBot: ${String(e?.message || e).slice(0, 200)}` } });
          }
        }
        if (msg.method === 'info' && h.tools) return reply({ result: { instructions: h.tools.instructions?.() || undefined } });
        if (msg.method === 'tools/list' && h.tools) return reply({ result: { tools: await h.tools.list() } });
        if (msg.method === 'tools/call' && h.tools) {
          const { listChanged, ...result } = await h.tools.call(String(p.name || ''), p.arguments ?? {}, ac.signal);
          return reply({ result, ...(listChanged ? { listChanged: true } : {}) });
        }
        return reply({ error: 'method not allowed' });
      } catch (e: any) {
        return reply({ error: String(e?.message || e).slice(0, 300) });
      }
    });
  }

  stop() {
    this.handlers.clear();
    try {
      this.server?.close();
    } catch {
      /* ignore */
    }
    this.server = null;
    this.starting = null;
    this.address = '';
  }
}
